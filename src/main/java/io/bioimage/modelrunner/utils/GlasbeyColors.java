    /**
     * Recommended for segmentation classes.
     *
     * classId 0 -> black (background)
     * classId 1 -> Glasbey blue
     * classId 2 -> Glasbey red
     * classId 3 -> Glasbey green
     * ...
     *
     * IDs above 255 cycle through the palette.
     */
    public static Color getColor(int classId) {
        if (classId <= 0) {
            return Color.BLACK;
        }

        // Skip Glasbey index 0 because it is white.
        int index = 1 + Math.floorMod(classId - 1, GLASBEY.length - 1);

        return new Color(GLASBEY[index]);
    }

    /**
     * Same as getColor(), but with an alpha value [0, 255].
     * Useful for overlays in Icy.
     */
    public static Color getColor(int classId, int alpha) {
        Color c = getColor(classId);

        return new Color(
            c.getRed(),
            c.getGreen(),
            c.getBlue(),
            alpha
        );
    }

    /**
     * Direct access to the original Glasbey LUT.
     *
     * index 0 -> white
     * index 1 -> blue
     * index 2 -> red
     * ...
     */
    public static Color getRawColor(int index) {
        index = Math.floorMod(index, GLASBEY.length);
        return new Color(GLASBEY[index]);
    }
